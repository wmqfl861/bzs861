#!/usr/bin/env python3
"""Record the independent, synthetic native cross-version publication review.

Temporary databases and executables are never saved in the repository. Each run
uses a new output directory; existing logs/results cannot be overwritten.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import io
import json
from pathlib import Path
import re
import shutil
import subprocess
import tarfile
import tempfile

BASELINE = "90ca7e93f9c96a43ff8d99b237638e4aa2aa2c63"
HERE = Path(__file__).resolve().parent
REPO = HERE.parents[2]


def digest(path: Path) -> str:
    value = hashlib.sha256()
    with path.open("rb") as source:
        for chunk in iter(lambda: source.read(1024 * 1024), b""):
            value.update(chunk)
    return value.hexdigest()


def inventory(root: Path, paths: list[Path]) -> dict[str, str]:
    return {path.relative_to(root).as_posix(): digest(path) for path in sorted(paths)}


def write_json(path: Path, value: object) -> None:
    path.write_text(json.dumps(value, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def now() -> str:
    return datetime.now(timezone.utc).isoformat()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--baseline-lib", type=Path, required=True)
    parser.add_argument("--current-lib", type=Path, required=True)
    parser.add_argument("--run-name", required=True)
    parser.add_argument("--cxx", default="c++")
    args = parser.parse_args()
    if not re.fullmatch(r"[a-z0-9][a-z0-9_-]{0,63}", args.run_name):
        parser.error("run-name must be a simple new lowercase directory name")
    baseline_lib = args.baseline_lib.resolve(strict=True)
    current_lib = args.current_lib.resolve(strict=True)
    compiler = shutil.which(args.cxx)
    if compiler is None:
        parser.error("C++ compiler was not found")
    destination = HERE / args.run_name
    destination.mkdir(exist_ok=False)
    commands: list[dict] = []
    original_paths = [*REPO.joinpath("src").rglob("*.cpp"), *REPO.joinpath("include").rglob("*.hpp"), REPO / "CMakeLists.txt"]
    harness_paths = [HERE / name for name in ("run_review.py", "create_schema6.cpp", "verify_upgrade.cpp", "verify_publication_epoch.cpp")]
    before = {
        "baseline_lib_sha256": digest(baseline_lib),
        "current_lib_sha256": digest(current_lib),
        "current_native_sources": inventory(REPO, original_paths),
        "review_sources": inventory(HERE, harness_paths),
    }
    result: dict = {
        "version": "bzs-independent-migration-review-1",
        "started_at": now(),
        "baseline_commit": BASELINE,
        "baseline_tree": subprocess.check_output(["git", "rev-parse", f"{BASELINE}^{{tree}}"], cwd=REPO, text=True).strip(),
        "baseline_lib": str(baseline_lib),
        "current_lib": str(current_lib),
        "compiler": compiler,
        "inputs_before": before,
        "scope": "Synthetic native WorkerPort fixtures; actual schema6 is generated by the preserved 0.1.4 library. No real HTTP and no broad suite rerun.",
        "schema_rewritten_by_fixture": False,
        "databases_retained_in_repository": False,
        "passed": False,
    }
    write_json(destination / "review.json", result)

    def run(label: str, argv: list[str], cwd: Path) -> Path:
        path = destination / f"{label}.log"
        started = now()
        with path.open("xb") as output:
            completed = subprocess.run(argv, cwd=cwd, stdout=output, stderr=subprocess.STDOUT, check=False)
        record = {"label": label, "argv": argv, "cwd": str(cwd), "started_at": started, "finished_at": now(),
                  "exit_code": completed.returncode, "log": path.name, "log_sha256": digest(path)}
        commands.append(record)
        write_json(destination / "commands.json", commands)
        if completed.returncode != 0:
            raise RuntimeError(f"{label} exited {completed.returncode}; see {path}")
        return path

    try:
        with tempfile.TemporaryDirectory(prefix="bzs-independent-migration-") as temporary:
            work = Path(temporary)
            baseline_source = work / "baseline"
            baseline_source.mkdir()
            archive_argv = ["git", "archive", "--format=tar", BASELINE, "include", "src", "tests/crawl.cpp", "CMakeLists.txt"]
            archive = subprocess.check_output(archive_argv, cwd=REPO)
            result["baseline_archive_command"] = archive_argv
            result["baseline_archive_sha256"] = hashlib.sha256(archive).hexdigest()
            with tarfile.open(fileobj=io.BytesIO(archive), mode="r:") as source:
                for member in source.getmembers():
                    target = (baseline_source / member.name).resolve()
                    if not target.is_relative_to(baseline_source) or not (member.isfile() or member.isdir()):
                        raise RuntimeError("Unexpected baseline archive member")
                source.extractall(baseline_source, filter="data")
            result["baseline_source_sha256"] = inventory(baseline_source, [p for p in baseline_source.rglob("*") if p.is_file()])
            shutil.copyfile(baseline_source / "tests/crawl.cpp", baseline_source / "baseline_crawl_tests.cpp")
            link = ["-lsqlite3", "-lcrypto", "-lxml2", "-ljson-c", "-pthread"]
            creator, upgrader, epoch = (work / name for name in ("create_schema6", "verify_upgrade", "verify_publication_epoch"))
            run("compile-schema6", [compiler, "-std=c++20", "-I", str(baseline_source / "include"), "-I", str(baseline_source),
                                    str(HERE / "create_schema6.cpp"), str(baseline_lib), *link, "-o", str(creator)], REPO)
            run("compile-upgrade", [compiler, "-std=c++20", "-I", str(REPO / "include"), str(HERE / "verify_upgrade.cpp"),
                                    str(current_lib), *link, "-o", str(upgrader)], REPO)
            run("compile-epoch", [compiler, "-std=c++20", "-I", str(REPO / "include"), str(HERE / "verify_publication_epoch.cpp"),
                                  str(current_lib), *link, "-o", str(epoch)], REPO)
            result["executables_before"] = {p.name: digest(p) for p in (creator, upgrader, epoch)}
            fixture = work / "fixture"
            create_log = run("create-schema6", [str(creator), str(fixture)], REPO)
            created = json.loads(create_log.read_text(encoding="utf-8"))
            if created["snapshot"]["meta"]["redirects"] != []:
                raise RuntimeError("Baseline fixture no longer demonstrates missing immutable intermediate-hop metadata")
            fixture_hash_before = digest(fixture / "db")
            upgraded = json.loads(run("verify-upgrade", [str(upgrader), str(fixture), str(work / "upgraded")], REPO).read_text(encoding="utf-8"))
            if len(upgraded) != 2 or {r["scenario"] for r in upgraded} != {"narrowed_scope", "explicit_empty"}:
                raise RuntimeError("Unexpected migration scenario set")
            for item in upgraded:
                for field in ("schema6_actual_crawl_fixture", "legacy_current_withdrawn", "legacy_frozen_withdrawn", "private_snapshot_and_evidence_retained", "complete_read_restores_new_current_only"):
                    if item[field] is not True:
                        raise RuntimeError(f"Migration check failed: {field}")
                if item["worker_calls"] != 1 or item["legacy_database_mutated_by_fixture"] is not False:
                    raise RuntimeError("Migration fixture call-count or mutation assertion failed")
            epochs = json.loads(run("verify-epoch", [str(epoch), str(fixture), str(work / "epochs")], REPO).read_text(encoding="utf-8"))
            expected = {(mode, inflight, child) for mode in ("rejected", "links_only") for inflight in (False, True) for child in (False, True)}
            if len(epochs) != 8 or {(r["mode"], r["inflight_relaxation"], r["new_child_scope"]) for r in epochs} != expected:
                raise RuntimeError("Unexpected publication generation scenario set")
            for item in epochs:
                if item["worker_calls"] != 2 or any(item[field] is not True for field in ("old_artifact_remains_restricted", "fts_and_non_fts_checked", "complete_read_restores_new_current_only")):
                    raise RuntimeError("Publication generation result failed")
            result["migration_results"], result["publication_epoch_results"] = upgraded, epochs
            result["fixture_database_sha256"] = fixture_hash_before
            result["pristine_fixture_unchanged"] = fixture_hash_before == digest(fixture / "db")
            result["executables_after"] = {p.name: digest(p) for p in (creator, upgrader, epoch)}
            if not result["pristine_fixture_unchanged"] or result["executables_before"] != result["executables_after"]:
                raise RuntimeError("Fixture database or executable changed unexpectedly")
        after_paths = [*REPO.joinpath("src").rglob("*.cpp"), *REPO.joinpath("include").rglob("*.hpp"), REPO / "CMakeLists.txt"]
        after = {"baseline_lib_sha256": digest(baseline_lib), "current_lib_sha256": digest(current_lib),
                 "current_native_sources": inventory(REPO, after_paths), "review_sources": inventory(HERE, harness_paths)}
        result["inputs_after"] = after
        result["inputs_unchanged"] = before == after
        if not result["inputs_unchanged"]:
            raise RuntimeError("Native or review inputs changed during independent verification")
        result["passed"] = True
    except BaseException as error:
        result["error"] = f"{type(error).__name__}: {error}"
        raise
    finally:
        result["finished_at"] = now()
        result["commands_sha256"] = digest(destination / "commands.json") if (destination / "commands.json").exists() else None
        write_json(destination / "review.json", result)
    print(json.dumps({"passed": True, "migration_scenarios": 2, "publication_epoch_scenarios": 8, "record": str(destination / "review.json")}, ensure_ascii=False))


if __name__ == "__main__":
    main()
